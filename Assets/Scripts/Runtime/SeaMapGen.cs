        // 记录本环的大致经纬包围盒(供窗口调试 / 快速跳过)
        static void AddLand(string name, double[][] pts)
        {
            if (pts.Length < 3) return;
            s_rings.Add(new Ring { name = name, pts = pts });
            RingNames = null;
            s_ringBox = null;          // 环表变了 → 求交用的包围盒缓存作废(懒重建)
            RefreshNames();
        }

        static void RefreshNames()
        {
            var a = new List<string>();
            foreach (var r in s_rings) a.Add(r.name);
            RingNames = a;
        }

        // 供离屏工具画"环的边", 目视检查顶点有无错位/自相交
        public static double[][] GetRingPts(string name)
        {
            if (s_rings.Count == 0) BuildData();
            foreach (var r in s_rings)
                if (r.name == name) return r.pts;
            return null;
        }

        static void AddIsle(string name, double cx, double cy, double rx, double ry, int seg = 20)
        {
            var a = new double[seg + 1][];
            for (int i = 0; i <= seg; i++)
