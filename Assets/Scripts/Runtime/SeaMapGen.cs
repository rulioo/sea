        public static bool LandAt(double lon, double lat) => LandAt(lon, lat, null);

        public static bool LandAt(double lon, double lat, string onlyRing)
        {
            if (s_rings.Count == 0) BuildData();
            foreach (var ring in s_rings)
            {
                if (onlyRing != null && ring.name != onlyRing) continue;
                if (PointInPoly(lon, lat, ring.pts)) return true;
            }
            return false;
        }

        static bool PointInPoly(double px, double py, double[][] poly)
        {
            bool inside = false;
            int n = poly.Length;
            for (int i = 0, j = n - 1; i < n; j = i++)
            {
                double xi = poly[i][0], yi = poly[i][1];
                double xj = poly[j][0], yj = poly[j][1];
                if (((yi > py) != (yj > py)) && (px < (xj - xi) * (py - yi) / (yj - yi) + xi))
                    inside = !inside;
            }
            return inside;
        }

        // =============================================================
        // 线段压陆判定(精确)
        //   场景: 航线是两个点之间的折线, 要知道"这一段有没有碰到陆地"。
        //   曾经用"沿线按 0.1° 采样再逐点 LandAt" —— 采样天生会从比步长还短的陆尖
        //   两侧跨过去, 实测漏掉过 0.08° 的贴岸(约一条船身长, 画面上就是黄虚线蹭过
        //   一小截海岸)。而 LandAt 本身是精确的多边形内外判定, 所以这里改用
        //   线段求交: 判决式的, 不漏。SeaRoute 的抽直与航线校验器都以它为准。
        // =============================================================

        static float[] s_ringBox;   // 每环 4 个数(minLon/minLat/maxLon/maxLat), 求交前粗筛用

        // 线段是否压陆: 端点落在陆地**内部**, 或与海岸线发生真穿越。
        //   端点落在海岸线上本身不算 —— 港点和格心都可能正好压在岸线上, 而 LandAt 对边界点的
        //   内外判定是任意的(恒定的, 但取哪边不由我们定)。见 SegCrossProper 的注释。
        public static bool SegmentHitsLand(double lon1, double lat1, double lon2, double lat2)
        {
            if (s_rings.Count == 0) BuildData();
            // 端点在陆地内部 → 压陆。港点建在陆上, 于是"进出港那一段"必然判真 —— 对, 那一段
            //   确实压陆, 只是它不该被画出来(见 SeaPlay.RebuildRouteLine)。
            if (LandAt(lon1, lat1) || LandAt(lon2, lat2)) return true;

            EnsureRingBoxes();
            double lox = Math.Min(lon1, lon2), hix = Math.Max(lon1, lon2);
            double loy = Math.Min(lat1, lat2), hiy = Math.Max(lat1, lat2);
            for (int r = 0; r < s_rings.Count; r++)
            {
                // 粗筛: 环的盒子与线段的盒子不相交 → 这一环整块跳过。跨洋的长弦要面对几百条
                //   海岸边, 没有这步就是 O(环×边) 逐条算; 有了它绝大多数环一眼挡掉。
                if (hix < s_ringBox[r * 4] || lox > s_ringBox[r * 4 + 2] ||
                    hiy < s_ringBox[r * 4 + 1] || loy > s_ringBox[r * 4 + 3]) continue;
                var p = s_rings[r].pts;
                for (int i = 0, j = p.Length - 1; i < p.Length; j = i++)
                    if (SegCrossProper(lon1, lat1, lon2, lat2, p[j][0], p[j][1], p[i][0], p[i][1]))
                        return true;
            }
            return false;
        }

        static void EnsureRingBoxes()
        {
            if (s_ringBox != null && s_ringBox.Length == s_rings.Count * 4) return;
            s_ringBox = new float[s_rings.Count * 4];
            for (int r = 0; r < s_rings.Count; r++)
            {
                var p = s_rings[r].pts;
                double x0 = double.MaxValue, y0 = double.MaxValue, x1 = double.MinValue, y1 = double.MinValue;
                for (int i = 0; i < p.Length; i++)
                {
                    double x = p[i][0], y = p[i][1];
                    if (x < x0) x0 = x;
                    if (x > x1) x1 = x;
                    if (y < y0) y0 = y;
                    if (y > y1) y1 = y;
                }
                s_ringBox[r * 4] = (float)x0; s_ringBox[r * 4 + 1] = (float)y0;
                s_ringBox[r * 4 + 2] = (float)x1; s_ringBox[r * 4 + 3] = (float)y1;
            }
        }

        // 两条线段是否"真穿越": 严格跨立(A、B 分居 CD 两侧, 且 C、D 分居 AB 两侧)。
        //   共线、端点相触这些退化情形一律不算 —— 它们是零宽接触, 不算"穿过了陆地"。
        //   但**必须**给叉积留一条零带。弦的端点正好落在海岸线上时(格心压岸的海格就是这样),
        //   Ori 在实数下是 0, 浮点下只剩 ~1e-15 的残差, 而 `> 0` 只看符号 —— 残差是正是负
        //   纯属舍入运气。实测维拉克鲁斯那格 (-95.875, 19.125) 正好落在海岸边
        //   (-96.1,19.2)→(-94.6,18.7) 上, 残差恰好为负, 于是"A 在 CD 直线上"被读成"A 跨到了
        //   CD 另一侧", 连向北/东北/东三条出海方向的弦全判压陆, 该格四面焊死 ——
        //   洪泛从 25 万格塌成 1 格, 维拉克鲁斯与其余 51 港全不通(A* 失败 51)。见 DiagFlood/DiagCell。
        //   零带的合法性: 若 AB 的某个端点落在 CD 的**直线**上, 两直线就只交于该点(或重合),
        //   而它是 AB 的端点、不是内部 —— 严格跨立本就不可能发生, 判"不穿越"是数学上正确的。
        //   量级: 坐标 ~1e2, 叉积舍入残差 ~1e-14; 任何有意义的跨立都 ≥1e-3。Eps 取 1e-9,
        //   两边各留五个数量级。
        //   代价是漏掉"穿过多边形顶点"的弦, 由校验器的细采样复核兜住, 见 ValidateRoutes。
        static bool SegCrossProper(double ax, double ay, double bx, double by,
                                   double cx, double cy, double dx, double dy)
        {
            const double Eps = 1e-9;
            double d1 = Ori(cx, cy, dx, dy, ax, ay);
            if (Math.Abs(d1) <= Eps) return false;    // A 在 CD 直线上 → 至多相触
            double d2 = Ori(cx, cy, dx, dy, bx, by);
            if (Math.Abs(d2) <= Eps) return false;    // B 同理
            if ((d1 > 0) == (d2 > 0)) return false;
            double d3 = Ori(ax, ay, bx, by, cx, cy);
            if (Math.Abs(d3) <= Eps) return false;    // C 在 AB 直线上
            double d4 = Ori(ax, ay, bx, by, dx, dy);
            if (Math.Abs(d4) <= Eps) return false;    // D 同理
            return (d3 > 0) != (d4 > 0);
        }

        // O→A→B 的叉积符号(>0 左转 / <0 右转 / =0 共线)
        static double Ori(double ox, double oy, double ax, double ay, double bx, double by)
            => (ax - ox) * (by - oy) - (ay - oy) * (bx - ox);

        static int _w, _h;
        static byte[] _rgba;
        static float[] _seaD, _landD;   // 单位=px

        public static int W => _w;
        public static int H => _h;

        static void Chamfer(float[] d)
        {
            int w = _w, h = _h;
            const float S = 1.41421356f;
            for (int it = 0; it < 2; it++)
            {
                for (int y = 0; y < h; y++)
                {
                    int baseIdx = y * w;
                    for (int x = 0; x < w; x++)
                    {
                        int i = baseIdx + x;
                        float v = d[i];
                        if (x > 0) v = Math.Min(v, d[i - 1] + 1f);
                        if (y > 0) v = Math.Min(v, d[i - w] + 1f);
                        if (x > 0 && y > 0) v = Math.Min(v, d[i - w - 1] + S);
                        if (x < w - 1 && y > 0) v = Math.Min(v, d[i - w + 1] + S);
                        d[i] = v;
                    }
                }
                for (int y = h - 1; y >= 0; y--)
                {
                    int baseIdx = y * w;
                    for (int x = w - 1; x >= 0; x--)
                    {
                        int i = baseIdx + x;
                        float v = d[i];
                        if (x < w - 1) v = Math.Min(v, d[i + 1] + 1f);
                        if (y < h - 1) v = Math.Min(v, d[i + w] + 1f);
                        if (x < w - 1 && y < h - 1) v = Math.Min(v, d[i + w + 1] + S);
                        if (x > 0 && y < h - 1) v = Math.Min(v, d[i + w - 1] + S);
                        d[i] = v;
                    }
                }
            }
        }

        // 生成世界地图 RGBA(底行 y=0 为最南; 每像素 4 字节 RGBA)
        // onlyRing 非空时只烘指定环(离屏逐块校对用)。
        public static byte[] Build(int pxPerDeg = PxPerDeg, string onlyRing = null)
        {
            if (s_rings.Count == 0) BuildData();
            double spanLon = Lon1 - Lon0, spanLat = Lat1 - Lat0;
            _w = (int)Math.Round(spanLon * pxPerDeg);
            _h = (int)Math.Round(spanLat * pxPerDeg);
            int n = _w * _h;

            var land = new bool[n];
            for (int y = 0; y < _h; y++)
            {
                double lat = Lat0 + (y + 0.5) / pxPerDeg;
                int baseIdx = y * _w;
                for (int x = 0; x < _w; x++)
                {
                    double lon = Lon0 + (x + 0.5) / pxPerDeg;
                    land[baseIdx + x] = LandAt(lon, lat, onlyRing);
                }
            }

            _seaD = new float[n];
            _landD = new float[n];
            const float INF = 1e9f;
            for (int i = 0; i < n; i++)
            {
                _seaD[i] = land[i] ? 0f : INF;
                _landD[i] = land[i] ? INF : 0f;
            }
            Chamfer(_seaD);     // 海洋侧: 到最近陆地的距离(px)
            Chamfer(_landD);    // 陆地侧: 到最近海岸的距离(px)

            var rgb = new byte[n * 4];
            float dp = pxPerDeg;
            for (int y = 0; y < _h; y++)
            {
                double lat = Lat0 + (y + 0.5) / pxPerDeg;
                int baseIdx = y * _w;
                for (int x = 0; x < _w; x++)
                {
                    double lon = Lon0 + (x + 0.5) / pxPerDeg;
                    int i = baseIdx + x;
                    int o = i * 4;
                    double r, g, b;
                    if (land[i])
                    {
                        double din = _landD[i] / dp;
                        bool arid = Arid(lon, lat);
                        bool snow = lat > 66 || (lat > 63 && lon < -20);
                        var rim = (0.80, 0.76, 0.58);
                        var zone = snow ? (0.86, 0.90, 0.93)
                                  : arid ? (0.62, 0.54, 0.35)
                                  : (0.32, 0.44, 0.26);
                        double k = Smooth(0.35, 2.0, din);
                        r = rim.Item1 + (zone.Item1 - rim.Item1) * k;
                        g = rim.Item2 + (zone.Item2 - rim.Item2) * k;
                        b = rim.Item3 + (zone.Item3 - rim.Item3) * k;
                        double noise = (Hash(lon, lat) - 0.5) * 0.05;
                        r = Clamp01(r + noise); g = Clamp01(g + noise); b = Clamp01(b + noise);
                    }
                    else
                    {
                        double dout = _seaD[i] / dp;
                        var surf = (0.46, 0.70, 0.66);
                        var shl = (0.10, 0.30, 0.35);
                        var deep = (0.030, 0.115, 0.168);
                        double k1 = Smooth(0.06, 0.95, dout);
                        double k2 = Smooth(2.2, 4.4, dout);
                        r = surf.Item1 + (shl.Item1 - surf.Item1) * k1;
                        g = surf.Item2 + (shl.Item2 - surf.Item2) * k1;
                        b = surf.Item3 + (shl.Item3 - surf.Item3) * k1;
                        r = r + (deep.Item1 - r) * k2;
                        g = g + (deep.Item2 - g) * k2;
                        b = b + (deep.Item3 - b) * k2;
                    }
                    if (!land[i])
                    {
                        double gx = NearestGrid(lon, 10.0) * dp;
                        double gy = NearestGrid(lat, 10.0) * dp;
                        if (gx < 0.55 || gy < 0.55)
                        {
                            double t = 0.05 * (1.0 - Math.Min(1.0, Math.Max(gx, gy)));
                            r = Clamp01(r + t); g = Clamp01(g + t); b = Clamp01(b + t);
                        }
                    }
                    rgb[o] = (byte)(Clamp01(r) * 255f + 0.5);
                    rgb[o + 1] = (byte)(Clamp01(g) * 255f + 0.5);
                    rgb[o + 2] = (byte)(Clamp01(b) * 255f + 0.5);
                    rgb[o + 3] = 255;
                }
            }
            _rgba = rgb;
            return rgb;
        }

        // 港点到最近陆地的距离(度): 海上>0 / 陆上内陆<0
        public static double CoastDistDeg(double lon, double lat)
        {
            if (_rgba == null) Build();
            double px = (lon - Lon0) * PxPerDeg;
            double py = (lat - Lat0) * PxPerDeg;
            int x = (int)Math.Round(px), y = (int)Math.Round(py);
            if (x < 0 || y < 0 || x >= _w || y >= _h) return 999.0;
            int i = y * _w + x;
            bool land = _landD[i] > _seaD[i];
            if (land) return -_landD[i] / PxPerDeg;
            return _seaD[i] / PxPerDeg;
        }

        static double Hash(double lon, double lat)
        {
            double s = Math.Sin(lon * 127.1 + lat * 311.7) * 43758.5453;
            return s - Math.Floor(s);
        }

        public static bool Arid(double lon, double lat)
        {
            if (lat >= 14 && lat <= 34 && lon >= -17 && lon <= 62) return true;
            if (lat >= 24 && lat <= 41 && lon >= 60 && lon <= 105) return true;
            if (lat >= -31 && lat <= -19 && lon >= 10 && lon <= 30) return true;
            if (lat >= 22 && lat <= 35 && lon >= -112 && lon <= -98) return true;
            return false;
        }

        static double NearestGrid(double v, double step)
        {
            double m = v - Math.Floor(v / step) * step;
            return Math.Min(m, step - m);
        }

        static double Smooth(double a, double b, double x)
        {
            double t = Math.Min(1.0, Math.Max(0.0, (x - a) / (b - a)));
            return t * t * (3 - 2 * t);
        }

        static double Clamp01(double v) => v < 0 ? 0 : (v > 1 ? 1 : v);
    }
